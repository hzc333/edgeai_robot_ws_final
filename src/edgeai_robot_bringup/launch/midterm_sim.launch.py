"""
Midterm check simulation (2026-11-12): arena, both robots and their stacks.

The arena is the single shared world of the midterm check, generated by P4
(edgeai_task_coordinator/test_assets/midterm.sdf, arena frame with the origin at
the lower-left corner). Robots spawn in the start area (config/sim/robots_midterm.yaml).

part:=1  robot_1 maps (nav_mode slam); robot_2 waits parked at midterm_robot_2 so
         robot_1 can see its chassis. SLAM and exploration belong to P2;
         dev_slam:=true starts SLAM Toolbox for P1 tests only. SLAM Toolbox anchors
         its map at robot_1's start pose (slam_map_origin:=midterm_robot_1).
part:=2  both robots on the pre-built map (P4 test_assets/midterm.yaml) with AMCL;
         relocalize each with start_pose_id midterm_robot_N.
"""

import os
from pathlib import Path
import tempfile
from xml.etree import ElementTree

from ament_index_python.packages import get_package_share_directory
from launch import LaunchDescription
from launch.actions import DeclareLaunchArgument, IncludeLaunchDescription, OpaqueFunction
from launch.actions import LogInfo
from launch.launch_description_sources import PythonLaunchDescriptionSource
from launch.substitutions import LaunchConfiguration

ROBOTS_FILE = 'robots_midterm.yaml'


def _as_bool(text):
    return text.strip().lower() in ('true', '1', 'yes')


def _world(path):
    """Point the P4 contact observer plugin at this machine's build, or drop it."""
    tree = ElementTree.parse(path)
    plugin = tree.find(".//plugin[@name='edgeai::Contacts']")
    note = None
    if plugin is not None:
        try:
            from edgeai_task_coordinator.physics import plugin_path
            plugin.set('filename', plugin_path())
        except (ImportError, RuntimeError) as error:
            tree.find('.//world').remove(plugin)
            note = f'midterm world without the P4 contact observer: {error}'
    with tempfile.NamedTemporaryFile(suffix='.sdf', prefix='midterm-world-',
                                     delete=False) as stream:
        tree.write(stream, encoding='utf-8', xml_declaration=True)
        return stream.name, note


def _include(package, launch_file, arguments):
    return IncludeLaunchDescription(
        PythonLaunchDescriptionSource(
            os.path.join(get_package_share_directory(package), 'launch', launch_file)),
        launch_arguments=arguments.items())


def _launch_setup(context, *args, **kwargs):
    part = LaunchConfiguration('part').perform(context)
    if part not in ('1', '2'):
        raise RuntimeError(f'part must be 1 or 2, got {part!r}')
    assets = Path(get_package_share_directory('edgeai_task_coordinator')) / 'test_assets'
    world_arg = LaunchConfiguration('world').perform(context)
    world, note = _world(world_arg or str(assets / 'midterm.sdf'))
    config_dir = LaunchConfiguration('config_dir').perform(context)
    common = {
        'config_dir': config_dir,
        'headless': LaunchConfiguration('headless').perform(context),
        'rviz': LaunchConfiguration('rviz').perform(context),
        'run_mode': LaunchConfiguration('run_mode').perform(context),
        'require_competition_state':
            LaunchConfiguration('require_competition_state').perform(context),
        'robots': 'robot_1,robot_2',
        'robots_file': ROBOTS_FILE,
        'world': world,
        'stack': LaunchConfiguration('stack').perform(context),
    }
    if part == '1':
        # SLAM Toolbox anchors the map at robot_1's start pose (see localization.py).
        origin = LaunchConfiguration('slam_map_origin').perform(context)
        common.update(nav_modes='robot_1:slam,robot_2:amcl', parked='robot_2:midterm_robot_2',
                      parked_map_origin=origin)
    else:
        common.update(nav_mode='amcl')
    actions = [_include('edgeai_robot_bringup', 'sim_multi_robot.launch.py', common)]
    if note:
        actions.append(LogInfo(msg=note))
    if part == '2':
        map_file = LaunchConfiguration('map').perform(context) or str(assets / 'midterm.yaml')
        actions.append(_include('edgeai_robot_navigation', 'dev_map_server.launch.py',
                                {'map': map_file, 'use_sim_time': 'true'}))
    elif _as_bool(LaunchConfiguration('dev_slam').perform(context)):
        # P1 test stand-in for P2's SLAM. SLAM Toolbox ignores map_start_pose while
        # mapping, so its map is anchored at robot_1's start pose (slam_map_origin).
        # It is a lifecycle node in Jazzy; its own launch file activates it.
        params = os.path.join(get_package_share_directory('edgeai_robot_description'),
                              'config', 'slam_toolbox.yaml')
        actions.append(_include('slam_toolbox', 'online_async_launch.py', {
            'slam_params_file': params, 'use_sim_time': 'true'}))
    return actions


def generate_launch_description():
    return LaunchDescription([
        DeclareLaunchArgument('part', default_value='1', description='1 | 2'),
        DeclareLaunchArgument('config_dir', default_value=os.environ.get('EDGEAI_CONFIG_DIR', ''),
                              description='Repository config directory (default: search)'),
        DeclareLaunchArgument('world', default_value='',
                              description='Default: P4 test_assets/midterm.sdf'),
        DeclareLaunchArgument('map', default_value='',
                              description='part 2 pre-built map; default: P4 '
                                          'test_assets/midterm.yaml'),
        DeclareLaunchArgument('headless', default_value='false'),
        DeclareLaunchArgument('rviz', default_value='false'),
        DeclareLaunchArgument('run_mode', default_value='development'),
        DeclareLaunchArgument('require_competition_state', default_value='true'),
        DeclareLaunchArgument('slam_map_origin', default_value='midterm_robot_1',
                              description='part 1: start pose at which the SLAM map is '
                                          'anchored; empty if SLAM uses the arena frame'),
        DeclareLaunchArgument('stack', default_value='true',
                              description='false: arena and robots only; the caller starts '
                                          'the robot stacks (P2 task1.launch.py '
                                          'scenario:=midterm)'),
        DeclareLaunchArgument('dev_slam', default_value='false',
                              description='part 1: start SLAM Toolbox (P1 tests until P2 '
                                          'provides SLAM)'),
        OpaqueFunction(function=_launch_setup),
    ])
